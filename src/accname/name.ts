
export const computeName = (
  element: Element,
): string => {
  //------------------------------------------------------------------------
  // 1. Initialization
  //------------------------------------------------------------------------
  let rootNode = element;
  let totalAccumulatedText = "";
  if (isNamingProhibited(rootNode)) {
    return "";
  }

  //------------------------------------------------------------------------
  // 2. Computation
  //------------------------------------------------------------------------

  // 2.1 hidden not referenced
  if (
    isHidden(element)

  ) {
    return "";
  }

  //------------------------------------------------------------------------
  // 3
  //------------------------------------------------------------------------
  return totalAccumulatedText;
}
